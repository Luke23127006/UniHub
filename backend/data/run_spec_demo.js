/**
 * UC07 — CSV Student Sync: Full Acceptance Criteria Demo
 *
 * Tests all 4 ACs from the spec in sequence with clear pass/fail output.
 *
 *   AC2: 20,000 rows processed in < 120s, no OOM
 *   AC3: 5 bad rows skipped, 19,995 upserted, all logged
 *   AC4: Running twice produces identical DB state (idempotency)
 *   AC5: A new student from the CSV can be found in the DB (login-ready)
 *
 * Usage (from backend/ directory):
 *   node data/run_spec_demo.js
 */
"use strict";

require("dotenv").config({ path: require("path").resolve(__dirname, "../.env") });
require("dotenv").config({ path: require("path").resolve(__dirname, "../../.env") });

const { execSync } = require("child_process");
const path = require("path");
const prisma = require("../src/config/db");

const CSV_PATH    = path.resolve(__dirname, "students_spec.csv");
const WORKER_PATH = path.resolve(__dirname, "../src/jobs/csvSyncWorker.js");
const GEN_PATH    = path.resolve(__dirname, "generate_spec_csv.js");

const EXPECTED_TOTAL   = 20_000;
const EXPECTED_VALID   = 19_995;
const EXPECTED_SKIPPED = 5;

// MSSV of a known-new student from the CSV (row 1, which is valid)
const SAMPLE_NEW_MSSV = "2019100001";

let passed = 0;
let failed = 0;

function check(label, ok, detail = "") {
  const icon = ok ? "✅" : "❌";
  const line = detail ? `${icon}  ${label} — ${detail}` : `${icon}  ${label}`;
  console.log(`  ${line}`);
  ok ? passed++ : failed++;
}

function separator(title) {
  console.log("");
  console.log(`${"─".repeat(55)}`);
  console.log(`  ${title}`);
  console.log(`${"─".repeat(55)}`);
}

function runWorker() {
  const t0 = Date.now();
  execSync(`node "${WORKER_PATH}" "${CSV_PATH}"`, {
    stdio: "inherit",
    env: process.env,
  });
  return (Date.now() - t0) / 1000;
}

async function cleanupPriorRuns() {
  // Remove students whose MSSVs are generated by generate_spec_csv.js
  // They all follow the pattern: 201X1XXXXX (year 2019-2024, seq 100001+)
  // Use the CsvSyncLog file_name as the scoping key instead.
  await prisma.csvSyncLog.deleteMany({ where: { file_name: "students_spec.csv" } });

  // Delete students whose email ends with @uni.edu.vn and mssv starts with 201
  // to avoid polluting the main dataset.
  await prisma.student.deleteMany({
    where: { email: { endsWith: "@uni.edu.vn" } },
  });
}

async function main() {
  console.log("═══════════════════════════════════════════════════════");
  console.log("  UC07 CSV Sync — Acceptance Criteria Demo");
  console.log("═══════════════════════════════════════════════════════");

  // ── Step 0: Generate CSV ───────────────────────────────────────────────────
  separator("Step 0 · Generate test CSV (20,000 rows)");
  execSync(`node "${GEN_PATH}"`, { stdio: "inherit", env: process.env });

  // ── Step 1: Clean slate ────────────────────────────────────────────────────
  separator("Step 1 · Clean slate (remove prior run data)");
  await cleanupPriorRuns();
  console.log("  ✓ Prior demo students and logs removed");

  // ── AC2 + AC3: First import run ────────────────────────────────────────────
  separator("AC2 + AC3 · First import run");
  console.log(`  File: students_spec.csv  (${EXPECTED_TOTAL.toLocaleString()} rows)`);
  console.log("");

  const elapsedSec = runWorker();

  // Fetch the sync log for this run
  const log1 = await prisma.csvSyncLog.findFirst({
    where: { file_name: "students_spec.csv" },
    orderBy: { created_at: "desc" },
  });

  separator("AC2 · Performance");
  check("Worker completed without crash",      log1?.status === "completed");
  check(`Elapsed time < 120s  (actual: ${elapsedSec.toFixed(1)}s)`, elapsedSec < 120,
        elapsedSec < 120 ? "PASS" : `FAIL — took ${elapsedSec.toFixed(1)}s`);

  separator("AC3 · Error handling (5 bad rows)");
  check(`Total rows read = ${EXPECTED_TOTAL}`,
        log1?.total_rows === EXPECTED_TOTAL,
        `actual: ${log1?.total_rows}`);
  check(`Processed (upserted) = ${EXPECTED_VALID.toLocaleString()}`,
        log1?.processed_rows === EXPECTED_VALID,
        `actual: ${log1?.processed_rows}`);
  check(`Skipped (bad rows) = ${EXPECTED_SKIPPED}`,
        log1?.skipped_rows === EXPECTED_SKIPPED,
        `actual: ${log1?.skipped_rows}`);
  check("Error details logged in CsvSyncLog",
        typeof log1?.error_details === "string" && log1.error_details.length > 0);

  if (log1?.error_details) {
    console.log("");
    console.log("  Logged error details:");
    log1.error_details.split("\n").forEach((line) => console.log(`    ${line}`));
  }

  // Count actual DB records
  const countAfterRun1 = await prisma.student.count({
    where: { email: { endsWith: "@uni.edu.vn" } },
  });
  check(`DB student count = ${EXPECTED_VALID.toLocaleString()} after run 1`,
        countAfterRun1 === EXPECTED_VALID,
        `actual: ${countAfterRun1}`);

  // ── AC4: Second run — idempotency ──────────────────────────────────────────
  separator("AC4 · Idempotency (run worker a second time, same CSV)");
  console.log("  Re-running worker on the same file...");
  console.log("");
  runWorker();

  const countAfterRun2 = await prisma.student.count({
    where: { email: { endsWith: "@uni.edu.vn" } },
  });
  check("DB count unchanged after second run (no duplicates)",
        countAfterRun2 === countAfterRun1,
        `run1=${countAfterRun1}, run2=${countAfterRun2}`);

  const log2 = await prisma.csvSyncLog.findFirst({
    where: { file_name: "students_spec.csv" },
    orderBy: { created_at: "desc" },
  });
  check("Second run also completed successfully", log2?.status === "completed");

  // ── AC5: New student is login-ready ───────────────────────────────────────
  separator("AC5 · New student is DB-ready (login-ready after sync)");
  const newStudent = await prisma.student.findUnique({
    where: { student_code: SAMPLE_NEW_MSSV },
  });
  check(`Student MSSV=${SAMPLE_NEW_MSSV} exists in DB`, newStudent != null);
  check("Student has valid email", newStudent?.email?.endsWith("@uni.edu.vn") ?? false,
        newStudent?.email ?? "—");
  check("Student has full_name", (newStudent?.full_name?.length ?? 0) > 0,
        newStudent?.full_name ?? "—");
  check("Student synced_at is set", newStudent?.synced_at != null);

  // ── Summary ────────────────────────────────────────────────────────────────
  console.log("");
  console.log("═══════════════════════════════════════════════════════");
  console.log(`  Results: ${passed} passed, ${failed} failed`);
  console.log("═══════════════════════════════════════════════════════");
  console.log("");

  await prisma.$disconnect();
  process.exit(failed > 0 ? 1 : 0);
}

main().catch((err) => {
  console.error("[Spec Demo] Unexpected error:", err.message);
  process.exit(1);
});
